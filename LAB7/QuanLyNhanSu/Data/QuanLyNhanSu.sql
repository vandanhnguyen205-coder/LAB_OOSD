-- 1. BANG PHONG BAN
CREATE TABLE PhongBan (
    MaPB NVARCHAR(20) PRIMARY KEY,
    TenPB NVARCHAR(100) NOT NULL,
    LoaiDonVi NVARCHAR(50) NOT NULL -- Phòng, Ban, Phân xưởng
);

-- 2. BANG CHUC VU
CREATE TABLE ChucVu (
    MaCV NVARCHAR(20) PRIMARY KEY,
    TenCV NVARCHAR(100) NOT NULL
);

-- 3. BANG NHAN VIEN
CREATE TABLE NhanVien (
    MaNV NVARCHAR(20) PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    GioiTinh NVARCHAR(10) NOT NULL,
    DienThoai NVARCHAR(15) NULL,
    DiaChi NVARCHAR(200) NULL,
    TrangThai NVARCHAR(50) NOT NULL DEFAULT N'Thử việc', -- Thử việc, Chính thức, Nghỉ việc
    MaPB NVARCHAR(20) NULL FOREIGN KEY REFERENCES PhongBan(MaPB)
);

-- 4. BANG QUYET DINH TUYEN DUNG
CREATE TABLE QuyetDinhTuyenDung (
    SoQD NVARCHAR(20) PRIMARY KEY,
    NgayQD DATE NOT NULL,
    NgayBatDauThuViec DATE NOT NULL,
    NgayKetThucThuViec DATE NOT NULL,
    LuongThuViec DECIMAL(18,2) NOT NULL,
    DieuKhoan NVARCHAR(MAX) NULL,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE,
    MaPB NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES PhongBan(MaPB),
    CONSTRAINT CK_TuyenDung_Ngay CHECK (NgayKetThucThuViec >= NgayBatDauThuViec)
);

-- 5. BANG HOP DONG
CREATE TABLE HopDong (
    SoHD NVARCHAR(20) PRIMARY KEY,
    LoaiHD NVARCHAR(50) NOT NULL, -- Dài hạn, Ngắn hạn
    NgayKy DATE NOT NULL,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NULL,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE
);

-- 6. BANG QUYET DINH LUONG
CREATE TABLE QuyetDinhLuong (
    SoQD NVARCHAR(20) PRIMARY KEY,
    NgayHieuLuc DATE NOT NULL,
    LuongCoBan DECIMAL(18,2) NOT NULL,
    PhuCapLuong DECIMAL(18,2) NOT NULL DEFAULT 0,
    PhuCapDocHai DECIMAL(18,2) NOT NULL DEFAULT 0,
    LyDo NVARCHAR(250) NULL,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE
);

-- 7. BANG QUYET DINH CHUC VU
CREATE TABLE QuyetDinhChucVu (
    SoQD NVARCHAR(20) PRIMARY KEY,
    NgayHieuLuc DATE NOT NULL,
    PhuCapChucVu DECIMAL(18,2) NOT NULL DEFAULT 0,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE,
    MaCV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES ChucVu(MaCV)
);

-- 8. BANG HO SO BIA HIEM
CREATE TABLE HoSoBaoHiem (
    MaHS NVARCHAR(20) PRIMARY KEY,
    SoBHXH NVARCHAR(50) NOT NULL,
    SoBHYT NVARCHAR(50) NOT NULL,
    TyLeBHXH FLOAT NOT NULL DEFAULT 0.08, -- 8%
    TyLeBHYT FLOAT NOT NULL DEFAULT 0.015, -- 1.5%
    NgayLap DATE NOT NULL,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE
);

-- 9. BANG BANG CHAM CONG
CREATE TABLE BangChamCong (
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE,
    Thang INT NOT NULL,
    Nam INT NOT NULL,
    NgayCongChuan INT NOT NULL DEFAULT 26,
    SoNgayCong FLOAT NOT NULL DEFAULT 0,
    PRIMARY KEY (MaNV, Thang, Nam),
    CONSTRAINT CK_ChamCong CHECK (SoNgayCong >= 0 AND SoNgayCong <= NgayCongChuan)
);

-- 10. BANG KE HOACH TUAN
CREATE TABLE KeHoachTuan (
    MaKH NVARCHAR(20) PRIMARY KEY,
    TuNgay DATE NOT NULL,
    DenNgay DATE NOT NULL,
    NoiDungPhanCong NVARCHAR(MAX) NULL,
    GioPhuTroiDuKien FLOAT NOT NULL DEFAULT 0,
    MaPB NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES PhongBan(MaPB)
);

-- 11. BANG PHIEU PHU TROI
CREATE TABLE PhieuPhuTroi (
    SoPhieu NVARCHAR(20) PRIMARY KEY,
    NgayPhuTroi DATE NOT NULL,
    SoGio FLOAT NOT NULL,
    HinhThuc NVARCHAR(50) NOT NULL -- Tăng ca, Ngày lễ, Ngày nghỉ
);

-- 12. BANG CHI TIET PHU TROI
CREATE TABLE ChiTietPhuTroi (
    SoPhieu NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES PhieuPhuTroi(SoPhieu) ON DELETE CASCADE,
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE,
    PRIMARY KEY (SoPhieu, MaNV)
);

-- 13. BANG QUYET DINH KHEN THUONG
CREATE TABLE QuyetDinhKhenThuong (
    SoQD NVARCHAR(20) PRIMARY KEY,
    NgayQD DATE NOT NULL,
    LoaiDoiTuong NVARCHAR(50) NOT NULL, -- Cá nhân, Tập thể
    LoaiKhenThuong NVARCHAR(100) NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL DEFAULT 0,
    NguoiKy NVARCHAR(100) NULL,
    MaNV NVARCHAR(20) NULL FOREIGN KEY REFERENCES NhanVien(MaNV),
    MaPB NVARCHAR(20) NULL FOREIGN KEY REFERENCES PhongBan(MaPB)
);

-- 14. BANG PHIEU CHI THUONG
CREATE TABLE PhieuChiThuong (
    SoPhieuChi NVARCHAR(20) PRIMARY KEY,
    NgayLap DATE NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL,
    HinhThuc NVARCHAR(50) NOT NULL, -- Chi tiền, Cộng vào lương
    SoQD NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES QuyetDinhKhenThuong(SoQD)
);

-- 15. BANG QUYET DINH KY LUAT
CREATE TABLE QuyetDinhKyLuat (
    SoQD NVARCHAR(20) PRIMARY KEY,
    NgayQD DATE NOT NULL,
    LoaiDoiTuong NVARCHAR(50) NOT NULL, -- Cá nhân, Tập thể
    HinhThucKyLuat NVARCHAR(100) NOT NULL,
    SoTienPhat DECIMAL(18,2) NOT NULL DEFAULT 0,
    NguoiKy NVARCHAR(100) NULL,
    MaNV NVARCHAR(20) NULL FOREIGN KEY REFERENCES NhanVien(MaNV),
    MaPB NVARCHAR(20) NULL FOREIGN KEY REFERENCES PhongBan(MaPB)
);

-- 16. BANG PHIEU THU PHAT
CREATE TABLE PhieuThuPhat (
    SoPhieuThu NVARCHAR(20) PRIMARY KEY,
    NgayLap DATE NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL,
    HinhThuc NVARCHAR(50) NOT NULL, -- Thu tiền, Trừ vào lương
    SoQD NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES QuyetDinhKyLuat(SoQD)
);

-- 17. BANG BANG LUONG
CREATE TABLE BangLuong (
    MaNV NVARCHAR(20) NOT NULL FOREIGN KEY REFERENCES NhanVien(MaNV) ON DELETE CASCADE,
    Thang INT NOT NULL,
    Nam INT NOT NULL,
    LuongCoBan DECIMAL(18,2) NOT NULL DEFAULT 0,
    PhuCap DECIMAL(18,2) NOT NULL DEFAULT 0,
    LuongNgayCong DECIMAL(18,2) NOT NULL DEFAULT 0,
    TienPhuTroi DECIMAL(18,2) NOT NULL DEFAULT 0,
    Thuong DECIMAL(18,2) NOT NULL DEFAULT 0,
    KhoanTruBH DECIMAL(18,2) NOT NULL DEFAULT 0,
    Phat DECIMAL(18,2) NOT NULL DEFAULT 0,
    ThucLinh DECIMAL(18,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (MaNV, Thang, Nam)
);
GO

